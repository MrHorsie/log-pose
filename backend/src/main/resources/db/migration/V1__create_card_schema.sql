-- Gameplay cards: one row per base card number (e.g. OP01-001).
CREATE TABLE cards (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_number  VARCHAR(32)  NOT NULL UNIQUE,
    name         VARCHAR(255) NOT NULL,
    category     VARCHAR(32)  NOT NULL,
    cost         INTEGER,
    power        INTEGER,
    counter      INTEGER,
    effect_text  TEXT,
    trigger_text TEXT
);

CREATE TABLE card_colors (
    card_id BIGINT      NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    color   VARCHAR(16) NOT NULL
);

CREATE TABLE card_attributes (
    card_id   BIGINT      NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    attribute VARCHAR(32) NOT NULL
);

CREATE TABLE card_traits (
    card_id BIGINT       NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    trait   VARCHAR(255) NOT NULL
);

-- Printings: one row per physical release (base, _p1 alt art, _r1 reprint, ...).
CREATE TABLE printings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id    VARCHAR(32)  NOT NULL UNIQUE,
    card_id      BIGINT       NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    set_code     VARCHAR(64)  NOT NULL,
    set_name     VARCHAR(255),
    rarity       VARCHAR(32),
    image_url    VARCHAR(512),
    block_number INTEGER
);

CREATE INDEX idx_cards_name_lower ON cards (LOWER(name));
CREATE INDEX idx_card_colors_card ON card_colors (card_id);
CREATE INDEX idx_card_attributes_card ON card_attributes (card_id);
CREATE INDEX idx_card_traits_card ON card_traits (card_id);
CREATE INDEX idx_printings_card ON printings (card_id);
CREATE INDEX idx_printings_set_code ON printings (set_code);
